// Embeds guide/*.md into src/guide/content.generated.ts so the chapters stay plain markdown to edit.
import { readFile, readdir, writeFile } from "node:fs/promises";

const directory = new URL("../guide/", import.meta.url);
const files = (await readdir(directory)).filter((name) => name.endsWith(".md")).sort();
const chapters = [];
for (const file of files) {
  const source = await readFile(new URL(file, directory), "utf8");
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source);
  if (!match) throw new Error(`${file} needs a --- front matter block`);
  const meta = Object.fromEntries(match[1].split("\n").filter(Boolean).map((line) => {
    const at = line.indexOf(":");
    return [line.slice(0, at).trim(), line.slice(at + 1).trim()];
  }));
  for (const key of ["id", "part", "title", "tagline"]) if (!meta[key]) throw new Error(`${file} is missing "${key}"`);
  chapters.push({ id: meta.id, part: meta.part, title: meta.title, tagline: meta.tagline, ...(meta.kinds ? { kinds: meta.kinds.split(",").map((kind) => kind.trim()) } : {}), markdown: match[2].trim() });
}
const ts = `// Generated by scripts/embed-guide.mjs from guide/*.md. Edit the markdown, not this file.\nimport type { Chapter } from "./chapter.js";\n\nexport const CHAPTERS: readonly Chapter[] = ${JSON.stringify(chapters, null, 2)} as Chapter[];\n`;
await writeFile(new URL("../src/guide/content.generated.ts", import.meta.url), ts);
console.log(`embedded ${chapters.length} chapters`);
